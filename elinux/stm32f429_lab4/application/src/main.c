#include <stdint.h>
#include "soc/stm32f429/irq.h"
#include "soc/stm32f429/rcc_regs.h"
#include "soc/stm32f429/tim_regs.h"


volatile uint32_t app_counter = 100;
volatile uint32_t app_status;

static void tim2_init(void)
{
    /* 1. Enable the TIM2 peripheral clock. */
    RCC_APB1ENR |= RCC_APB1ENR_TIM2EN;
    (void)RCC_APB1ENR;

    /* 2. Stop TIM2 while configuring it. */
    TIM2_CR1 = 0u;
    TIM2_DIER = 0u;

    /* 3. Configure the timer frequency. */
    TIM2_PSC = 8399u;
    TIM2_ARR = 999u;
    TIM2_CNT = 0u;

    /* 4. Generate an update event to load the prescaler. */
    TIM2_EGR = 1u;

    /* Clear the update flag generated by the event. */
    TIM2_SR = 0u;

    /* 5. Configure the NVIC interrupt. */
    nvic_set_priority(IRQ_TIM2, 5u);
    nvic_clear_pending(IRQ_TIM2);
    nvic_enable_irq(IRQ_TIM2);

    /* 6. Enable TIM2's update interrupt. */
    TIM2_DIER = 1u;

    /* 7. Start the timer. */
    TIM2_CR1 = 1u;
}

int main(void)
{
    app_status = app_counter + 50;

    tim2_init();

    /*
     * The bootloader disables interrupts before handing off control.
     * Re-enable them only after the application is configured.
     */
    __asm volatile ("cpsie i" ::: "memory");

    while (1)
    {
        app_counter++;
    }

    return 0;
}